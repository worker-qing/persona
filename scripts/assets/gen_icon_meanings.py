#!/usr/bin/env python3
"""Write Android's icon meanings from spec/icons/meanings.json (#4209).

Each entry names an iPhone icon meaning (`Theme.Icon.<meaning>` in apple/Shared/Design/Icons.swift), its SF Symbol, and
the Phosphor glyph Android draws for it (one of the names scripts/assets/gen_phosphor_icons.py generates into
`PhIcons`). The output is `PersonaIcons`, an object of meaning-named properties pointing at `PhIcons`, so pages say what
an icon means and the glyph stays chosen in one place.

    python3 scripts/assets/gen_icon_meanings.py            # write the Kotlin file
    python3 scripts/assets/gen_icon_meanings.py --check    # exit 1 when it is stale; write nothing
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "spec/icons/meanings.json"
KOTLIN = ROOT / "android/core/designsystem/src/main/kotlin/persona/core/designsystem/icons/PersonaIcons.kt"
KEYWORDS = {"as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null",
            "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var",
            "when", "while"}


def pascal(glyph):
    """`arrow-square-out` -> `ArrowSquareOut`, as gen_phosphor_icons.py names the PhIcons properties."""
    return "".join(part.capitalize() for part in glyph.split("-"))


def load(source=SOURCE):
    data = json.loads(Path(source).read_text(encoding="utf-8"))
    meanings = data["meanings"]
    if set(data) - {"$description", "meanings"}:
        raise ValueError("meanings.json holds $description and meanings only")
    for name, entry in meanings.items():
        if set(entry) != {"sf", "phosphor"}:
            raise ValueError(f"{name}: an entry has exactly sf and phosphor")
    return meanings


def render(meanings):
    lines = [
        "// Generated by scripts/assets/gen_icon_meanings.py from spec/icons/meanings.json; do not edit.",
        "package persona.core.designsystem.icons",
        "",
        "/**",
        " * The iPhone's icon meanings (`Theme.Icon` in apple/Shared/Design/Icons.swift), each drawn with its Phosphor glyph. Pages",
        " * use these names, so one meaning keeps one icon (docs/android/android-design.md, \"2.3 Rules for writing pages\").",
        " */",
        "object PersonaIcons {",
    ]
    for name in sorted(meanings):
        entry = meanings[name]
        prop = f"`{name}`" if name in KEYWORDS else name
        lines.append(f"    /** SF Symbol `{entry['sf']}`. */")
        lines.append(f"    val {prop}: PhIcon get() = PhIcons.{pascal(entry['phosphor'])}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description="Write PersonaIcons.kt from spec/icons/meanings.json")
    parser.add_argument("--check", action="store_true", help="exit 1 when the Kotlin file is stale; write nothing")
    args = parser.parse_args(argv)
    text = render(load())
    if args.check:
        if not KOTLIN.is_file() or KOTLIN.read_text(encoding="utf-8") != text:
            print(f"stale: {KOTLIN.relative_to(ROOT)}; run python3 scripts/assets/gen_icon_meanings.py", file=sys.stderr)
            return 1
        print(f"PersonaIcons.kt is current ({len(load())} meanings)")
        return 0
    KOTLIN.write_text(text, encoding="utf-8")
    print(f"wrote {KOTLIN.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
