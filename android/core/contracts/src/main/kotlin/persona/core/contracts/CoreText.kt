    /** The English words with [args] filled in, for logs and messages; the screen uses the app's resources. */
    fun english(): String = when (key) {
        Key.Verbatim -> args.first().toString()
        Key.Joined -> args.drop(1).map { (it as CoreText).english() }.filter(String::isNotEmpty).joinToString(args.first().let { if (it is CoreText) it.english() else it.toString() })
        // The count is the raw number: in thousands, stepping up to millions, as the English strings read it (#4182).
        Key.CompactCount -> compactCount((args.first() as Number).toLong(), Key.CompactUnit.english.toLong(),
            { String.format(java.util.Locale.ROOT, key.english, it) }, { "${it}M" })
        else -> if (args.isEmpty()) key.english else String.format(java.util.Locale.ROOT, key.english, *args.map { if (it is CoreText) it.english() else it }.toTypedArray())
    }

    companion object {
        fun of(key: Key, vararg args: Any): CoreText = CoreText(key, args.toList())

        /**
         * Turns [CoreText] into the app's language where no resources are at hand (an exception's message, the data
         * repositories' state): the app sets it at start (`CoreText.words = { it.resolve(app) }`); unset it is English (unit tests: Chinese, [CoreTextFallback]).
         */
        @Volatile var words: (CoreText) -> String = CoreTextFallback::words

        /** Words that are already final (a name, the hub's own reason), shown as they are. */
        fun plain(text: String): CoreText = CoreText(Key.Verbatim, listOf(text))

        /** [parts] in a row with [separator] between them ("3 working · 1 done"); empty parts are left out. */
        fun joined(separator: String, parts: List<CoreText>): CoreText = CoreText(Key.Joined, listOf<Any>(separator) + parts)

        /** [joined] with a separator that differs by language (a full-width comma, ", "). */
        fun joined(separator: CoreText, parts: List<CoreText>): CoreText = CoreText(Key.Joined, listOf<Any>(separator) + parts)
    }
}

/** A failure whose message the app shows as [text] in its own language; the exception's message is for logs. */
interface CoreTextFailure {
    val text: CoreText
}

/** A failure that says [text]; its message is [text] in the app's language ([CoreText.words]). */
open class CoreTextException(final override val text: CoreText, cause: Throwable? = null) : Exception(text.english(), cause), CoreTextFailure {
    /** The words in the app's language ([CoreText.words]), wherever the message is shown as it is. */
    override val message: String get() = CoreText.words(text)
}
